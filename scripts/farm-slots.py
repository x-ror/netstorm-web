#!/usr/bin/env python3
"""Write packages/client/src/farm-slots.ts: for each Fury's Edge Farm picture, the slot of
edgefarm.type that holds each frame number of the isle.type rim frames.

edgefarm.type lists its frames in the order of isle.type, and its farm pictures carry the frame
numbers of the rim pictures they stand for: efarm.gif #17 is the farm on risle.gif #17.

Usage: farm-slots.py <original/all-assets/sprites> <packages/client/src/farm-slots.ts>
"""
import json
import pathlib
import sys

SETS = {"neutral": "efarm.gif", "thunder": "thfarm.gif", "wind": "wefarm.gif", "rain": "raefarm.gif"}


def main() -> None:
    source, target = map(pathlib.Path, sys.argv[1:3])
    index = json.loads((source / "index.json").read_text())["edgefarm"]
    lines = [
        "/** Generated by scripts/farm-slots.py from edgefarm.type: by the Fury of the ground, the slot",
        " * of the Edge Farm on each rim frame number of isle.type. */",
        "/* oxlint-disable no-magic-numbers -- data of the original */",
        "export const FARM_SLOTS: Readonly<Record<string, Readonly<Record<number, number>>>> = {",
    ]
    for name, gif in SETS.items():
        found = {e["frame"]: int(slot) for slot, e in index.items() if e["gif"].lower() == gif}
        body = ", ".join(f"{frame}: {slot}" for frame, slot in sorted(found.items()))
        lines.append(f"  {name}: {{ {body} }},")
    lines += ["};", "/* oxlint-enable no-magic-numbers */", ""]
    target.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
