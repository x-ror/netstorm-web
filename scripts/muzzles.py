#!/usr/bin/env python3
"""Write the launch point of each frame of the guns into the client.

Every frame of d/_shapes.shp has a 0x24-byte record before the header scripts/unshp.py reads. Its
two int16 at +0x20/+0x22 are the point a missile leaves from, or where the Disc Thrower's disc sits
on its arm, in pixels from the frame's hot spot (Missile.cpp FUN_004a4b70, FUN_00482870 of
netstorm.game 10.82). The game reads them from the mapped file as they are.

Usage: muzzles.py <original/game/Netstorm> <packages/client/src/muzzles.ts>
"""
import os
import struct
import sys

GUNS = {'suncannon': 28, 'thundercannon': 36, 'raincannon': 12, 'windarcher': 100, 'sunarcher': 33}
RECORD = 0x24
POINT = 0x20


def main() -> None:
    game_dir, out = sys.argv[1:3]
    shp = open(os.path.join(game_dir, 'd', '_shapes.shp'), 'rb').read()
    tables, at = [], 0
    while shp[at:at + 4] == b'1.10':
        count = struct.unpack_from('<I', shp, at + 4)[0]
        tables.append(at)
        at += 8 + 8 * count
    game = open(os.path.join(game_dir, 'netstorm.game'), 'rb').read()
    names = [n.decode('latin-1').lower() for n in game[game.index(b'dude\0'):].split(b'\0') if n]
    lines = []
    for name, slots in GUNS.items():
        table = tables[names.index(name)]
        points = []
        for slot in range(slots):
            offset = struct.unpack_from('<I', shp, table + 8 + 8 * slot)[0]
            points.append(struct.unpack_from('<2h', shp, table + offset - RECORD + POINT))
        lines.append(f"  {name}: [{', '.join(f'[{x}, {y}]' for x, y in points)}],")
    with open(out, 'w') as file:
        file.write(
            '/** Generated by scripts/muzzles.py from d/_shapes.shp: by slot, the point each frame of a\n'
            " * gun launches its missile from (the Disc Thrower's arm: where its disc sits), in pixels\n"
            " * from the frame's hot spot. */\n"
            '/* oxlint-disable no-magic-numbers -- data of the original */\n'
            'export const MUZZLES: Readonly<Record<string, readonly (readonly [number, number])[]>> = {\n'
            + '\n'.join(lines) + '\n};\n')


if __name__ == '__main__':
    main()
